package com.forensicai.report;

import com.forensicai.ai.AiDTOs;
import com.lowagie.text.*;
import com.lowagie.text.pdf.*;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.Instant;

@Service
public class PdfReportService {

    public byte[] generateCaseReport(AiDTOs.AiAnalyzeResponse caseData) {
        try (ByteArrayOutputStream baos = new ByteArrayOutputStream()) {
            Document document = new Document(PageSize.A4, 36, 36, 40, 40);
            PdfWriter writer = PdfWriter.getInstance(document, baos);
            document.open();

            // Fonts
            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18, new Color(7, 10, 18));
            Font subTitleFont = FontFactory.getFont(FontFactory.HELVETICA, 10, new Color(100, 116, 139));
            Font h2Font = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12, new Color(6, 182, 212));
            Font boldFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.BLACK);
            Font bodyFont = FontFactory.getFont(FontFactory.HELVETICA, 9, new Color(30, 41, 59));
            Font disclaimerFont = FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 8, new Color(180, 83, 9));

            // Header Banner
            Paragraph header = new Paragraph("ForensicAI: Crime Analysis & Legal Mapping Report", titleFont);
            header.setAlignment(Element.ALIGN_CENTER);
            document.add(header);

            Paragraph meta = new Paragraph("Case Dossier: " + caseData.caseId() + " | Generated: " + Instant.now(), subTitleFont);
            meta.setAlignment(Element.ALIGN_CENTER);
            meta.setSpacingAfter(12);
            document.add(meta);

            // Educational Disclaimer Box
            PdfPTable discTable = new PdfPTable(1);
            discTable.setWidthPercentage(100);
            PdfPCell discCell = new PdfPCell(new Phrase("EDUCATIONAL ONLY: This analysis is generated by AI for law and forensic trainees. It does not constitute legal counsel or a binding court ruling. Consult an advocate of the Bar Council of India.", disclaimerFont));
            discCell.setBackgroundColor(new Color(254, 243, 199));
            discCell.setBorderColor(new Color(245, 158, 11));
            discCell.setPadding(8);
            discTable.addCell(discCell);
            discTable.setSpacingAfter(15);
            document.add(discTable);

            // Section 1: Applicable Penal Codes (Table)
            document.add(new Paragraph("1. APPLICABLE OFFENCES & STATUTORY MAPPING", h2Font));
            PdfPTable table = new PdfPTable(4);
            table.setWidthPercentage(100);
            table.setWidths(new float[]{1.5f, 1.5f, 3.5f, 1.5f});
            table.setSpacingBefore(6);
            table.setSpacingAfter(12);

            addTableHeader(table, "Act", "Section", "Title & Punishment", "Confidence");

            for (AiDTOs.SectionDTO sec : caseData.sections()) {
                table.addCell(new Phrase(sec.act(), bodyFont));
                table.addCell(new Phrase(sec.section(), boldFont));
                table.addCell(new Phrase(sec.title() + "\nPunishment: " + sec.punishment(), bodyFont));
                table.addCell(new Phrase(String.format("%.0f%%", sec.confidence() * 100), bodyFont));
            }
            document.add(table);

            // Section 2: Procedural Status
            document.add(new Paragraph("2. PROCEDURAL CLASSIFICATION", h2Font));
            Paragraph proc = new Paragraph(
                    "Arrest Classification: " + (caseData.status().cognizable() ? "COGNIZABLE (Arrest without warrant)" : "NON-COGNIZABLE") + "\n" +
                    "Bail Status: " + (caseData.status().bailable() ? "BAILABLE" : "NON-BAILABLE (Judicial discretion)") + "\n" +
                    "Compounding: " + (caseData.status().compoundable() ? "COMPOUNDABLE" : "NON-COMPOUNDABLE") + "\n" +
                    "Competent Trial Court: " + caseData.status().triableBy(),
                    bodyFont
            );
            proc.setSpacingBefore(4);
            proc.setSpacingAfter(12);
            document.add(proc);

            // Section 3: Forensic Evidence Checklist
            document.add(new Paragraph("3. FORENSIC EVIDENCE & CHAIN OF CUSTODY PROTOCOLS", h2Font));
            PdfPTable evTable = new PdfPTable(3);
            evTable.setWidthPercentage(100);
            evTable.setWidths(new float[]{1.5f, 3f, 4.5f});
            evTable.setSpacingBefore(6);
            evTable.setSpacingAfter(12);
            addTableHeader(evTable, "Category", "Evidence Item", "Preservation / Collection Protocol");

            for (AiDTOs.ForensicEvidenceDTO ev : caseData.forensicEvidence()) {
                evTable.addCell(new Phrase(ev.category().toUpperCase(), boldFont));
                evTable.addCell(new Phrase(ev.item(), bodyFont));
                evTable.addCell(new Phrase(ev.notes(), bodyFont));
            }
            document.add(evTable);

            // Section 4: Adversarial Defense Critique
            document.add(new Paragraph("4. ADVERSARIAL DEFENSE LAWYER CRITIQUE", h2Font));
            for (AiDTOs.DefenseCritiqueDTO crit : caseData.defenseCritique()) {
                Paragraph critP = new Paragraph(
                        "Defense Challenge: " + crit.argument() + "\n" +
                        "Vulnerability: " + crit.weakness() + "\n" +
                        "Counter-Strategy: " + crit.counter(),
                        bodyFont
                );
                critP.setSpacingBefore(4);
                critP.setSpacingAfter(6);
                document.add(critP);
            }

            document.close();
            return baos.toByteArray();
        } catch (Exception e) {
            throw new RuntimeException("Failed to generate PDF legal report", e);
        }
    }

    private void addTableHeader(PdfPTable table, String... headers) {
        Font headerFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9, Color.WHITE);
        for (String h : headers) {
            PdfPCell cell = new PdfPCell(new Phrase(h, headerFont));
            cell.setBackgroundColor(new Color(11, 17, 32));
            cell.setPadding(6);
            table.addCell(cell);
        }
    }
}
